// Fire form shares anatomy, not colors: white cap/shirt and red overalls.
// A single substitution pass avoids accidentally remapping newly replaced pixels.
function fireRows(rows: readonly string[]): readonly string[] {
  return rows.map((row) => row.replace(/[28]/g, (pixel) => pixel === '2' ? '5' : '2'));
}

